 private void tampilkanRingkasan() {
    String kelas;
    if (RbEkonomi.isSelected()) {
        kelas = "Ekonomi";
    } else if (RbBisnis.isSelected()) {
        kelas = "Bisnis";
    } else {
        kelas = "Eksekutif";
    }

    List<String> fasilitas = new ArrayList<>();
    for (JCheckBox cb : List.of(CbBagasi, CbMakanan, CbAsuransi)) {
        if (cb.isSelected()) {
            fasilitas.add(cb.getText());
        }
    }

    String pesan = "Nama: " + TfNama.getText()
            + "\nNo HP: " + TfHp.getText()
            + "\nKota Tujuan: " + Kota.getSelectedItem()
            + "\nKelas: " + kelas
            + "\nFasilitas: " + (fasilitas.isEmpty() ? "-" : String.join(", ", fasilitas))
            + "\nCatatan: " + (Ta.getText().isBlank() ? "-" : Ta.getText());

    JOptionPane.showMessageDialog(this, pesan, "Ringkasan Pesanan",
            JOptionPane.INFORMATION_MESSAGE);
}

private void gantiTema(boolean gelap) {
    if (gelap) {
        FlatDarkLaf.setup();
    } else {
        FlatLightLaf.setup();
    }
    FlatLaf.updateUI();
    TgGelap.setText(gelap ? "Mode Terang" : "Mode Gelap");
}
